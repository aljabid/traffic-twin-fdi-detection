from __future__ import annotations

import argparse
import base64
import os
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec


def _c_byte_array(name: str, data: bytes) -> str:
    body = ", ".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[{len(data)}] = {{{body}}};"


def provision(
    device_id: str,
    out_dir: Path,
    *,
    config_out: Path | None = None,
    extends: str = "field_trial.yaml",
    replay_tolerance_seconds: int = 30,
) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    aes_key = os.urandom(32)
    private_key = ec.generate_private_key(ec.SECP256R1())
    private_pem = private_key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    )
    public_pem = private_key.public_key().public_bytes(
        serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo
    )

    private_path = out_dir / f"{device_id}.private.pem"
    private_path.write_bytes(private_pem)

    indented_public = "\n".join(
        "        " + line for line in public_pem.decode().splitlines()
    )
    config_fragment = (
        "security:\n"
        "  backend: preshared\n"
        f"  replay_tolerance_seconds: {replay_tolerance_seconds}\n"
        "  preshared_keys:\n"
        f"    - device_id: {device_id}\n"
        f"      aes_key_b64: \"{base64.b64encode(aes_key).decode()}\"\n"
        "      public_key_pem: |\n"
        f"{indented_public}\n"
    )
    config_path = out_dir / f"{device_id}.security.yaml"
    config_path.write_text(config_fragment, encoding="utf-8")

    pem_c_literal = "\\n".join(private_pem.decode().splitlines())
    header = (
        "// Generated by smart-city-provision-device. Emulated field trial only.\n"
        "#pragma once\n"
        "#include <stdint.h>\n\n"
        f"#define DEVICE_ID \"{device_id}\"\n"
        f"#define DEVICE_SESSION_ID \"psk-{device_id}\"\n\n"
        f"{_c_byte_array('DEVICE_AES_KEY', aes_key)}\n\n"
        f"static const char DEVICE_PRIVATE_KEY_PEM[] =\n    \"{pem_c_literal}\\n\";\n"
    )
    header_path = out_dir / f"{device_id}.h"
    header_path.write_text(header, encoding="utf-8")

    written = {"private_key": private_path, "config": config_path, "header": header_path}

    if config_out is not None:
        config_out.parent.mkdir(parents=True, exist_ok=True)
        config_out.write_text(
            f"# Generated by smart-city-provision-device — contains a secret key, do not commit.\n"
            f"extends: {extends}\n{config_fragment}",
            encoding="utf-8",
        )
        written["runnable_config"] = config_out

    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--device-id", default="wokwi-esp32-01")
    parser.add_argument("--output-dir", default="field_trial/keys")
    parser.add_argument(
        "--config-out",
        default="configs/field_trial_secure.local.yaml",
        help="write a ready-to-run daemon config here (contains the AES key; git-ignored via *.local)",
    )
    parser.add_argument("--extends", default="field_trial_calibrated.yaml")
    parser.add_argument(
        "--replay-tolerance",
        type=int,
        default=600,
        help="replay-guard timestamp window in seconds; the emulated ESP32 clock "
        "runs at sim rate (~0.4x wall) so the field trial needs a wide window",
    )
    args = parser.parse_args(argv)

    written = provision(
        args.device_id,
        Path(args.output_dir),
        config_out=Path(args.config_out) if args.config_out else None,
        extends=args.extends,
        replay_tolerance_seconds=args.replay_tolerance,
    )
    for label, path in written.items():
        print(f"{label}: {path}")
    print(
        "\nRun the daemon:  smart-city-live-ingest --config "
        f"{args.config_out}\n"
        f"Copy {written['header'].name} into the Wokwi project as device_key.h."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
